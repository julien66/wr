def sort_key(label):
    """Clé de tri alphabétique sans accents ni casse : « Équateur » se range avec les E, « Österreich » avec les O."""
    s = unicodedata.normalize("NFKD", label)
    return "".join(c for c in s if not unicodedata.combining(c)).casefold()
